-- =====================================================================
-- Mfano Bora Africa Chatbot - MySQL Schema
-- Replaces the original PostgreSQL/pgvector design with a lightweight
-- MySQL 8.x schema. Retrieval is done with MySQL FULLTEXT search
-- (InnoDB) instead of a dedicated vector database, keeping the backend
-- lightweight and easy to host alongside the PHP website.
-- An optional `embedding_json` column is included so the FastAPI layer
-- can later upgrade to embedding re-ranking without a schema change.
-- =====================================================================

CREATE DATABASE IF NOT EXISTS mfano_bora_chatbot
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE mfano_bora_chatbot;

-- ---------------------------------------------------------------------
-- 1. Admin users (RBAC) - consumed by admin-php
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin_users (
    user_id         INT AUTO_INCREMENT PRIMARY KEY,
    username        VARCHAR(80)  NOT NULL UNIQUE,
    email           VARCHAR(150) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    role            ENUM('superadmin','editor','viewer') NOT NULL DEFAULT 'viewer',
    is_active       TINYINT(1) NOT NULL DEFAULT 1,
    created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at   DATETIME NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 2. Knowledge base categories (Task 4: Information Classification)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS kb_categories (
    category_id     INT AUTO_INCREMENT PRIMARY KEY,
    name            VARCHAR(100) NOT NULL UNIQUE,
    description     VARCHAR(255) NULL
) ENGINE=InnoDB;

